//! End-to-end SraVaani transcription, gated on the reference decode.
//!
//! `decode_golden.json` holds the token ids and word timings produced by the
//! model's own TorchScript graphs through the reference TDT loop in
//! `modeling_sravaani.py`. This test asserts the Rust decode produces the
//! **same token ids**.
//!
//! That is a strict assertion, and it is the point. A change in the decode
//! semantics -- advancing the LSTM state on a blank, dropping the `max_symbols`
//! guard, mis-slicing the duration logits -- produces a transcript that still
//! reads as plausible Hindi. Comparing token ids against the reference is the
//! only check that catches it. Comparing the *text* would not: two different
//! token sequences can normalise to the same string.
//!
//! The fixture is generated by `scripts/make_golden.py` and contains token ids
//! and timings for 40 seconds of real meeting speech. It contains no user
//! audio, and the recording it came from is not in the repository.

use std::path::PathBuf;
use std::time::Instant;

use vaani_asr::engine::{AsrEngine, AudioChunk};
use vaani_asr::{EngineArtifacts, SraVaaniEngine, artifacts_in, default_dir};
use vaani_core::Time;
use vaani_inference::{MachineCapabilities, Provider, runtime};

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("crate is under <root>/crates/vaani-asr")
        .to_path_buf()
}

fn golden() -> Option<PathBuf> {
    let p = repo_root()
        .join("tests")
        .join("fixtures")
        .join("sravaani")
        .join("decode_golden.json");
    p.is_file().then_some(p)
}

#[derive(serde::Deserialize)]
struct DecodeGolden {
    seconds: f64,
    sample_rate: u32,
    encoder_frames: usize,
    decode_steps: usize,
    frame_seconds: f64,
    token_ids: Vec<i32>,
    text: String,
    words: Vec<GoldenWord>,
}

#[derive(serde::Deserialize)]
struct GoldenWord {
    word: String,
    start: f64,
    end: f64,
}

fn skip(reason: &str) {
    println!("skipping: {reason}");
}

/// Open the engine on the GPU, or report precisely what is missing.
fn engine() -> Option<SraVaaniEngine> {
    if !runtime::location().is_present() {
        skip("ONNX Runtime absent; run scripts\\fetch_runtime.ps1");
        return None;
    }
    let dir = default_dir();
    if !dir.join("encoder.fp16.onnx").is_file() {
        skip("encoder.fp16.onnx absent; run scripts\\export_sravaani_onnx.py");
        return None;
    }
    let caps = detect();
    match vaani_asr::open_sravaani(&artifacts_in(&dir), Provider::Auto, &caps) {
        Ok(e) => Some(e),
        Err(e) => {
            skip(&format!("could not open the engine: {}", e.user.title));
            None
        }
    }
}

/// Probe the machine. Real detection, not a default: the VRAM budget and the
/// execution provider both come from this, and a default would silently pick
/// the CPU.
fn detect() -> MachineCapabilities {
    let loc = runtime::location();
    vaani_inference::capability::detect(&loc.provider_dirs)
}

/// A synthetic chunk the length of the golden clip.
///
/// We deliberately do NOT ship the audio: the fixture is token ids only, so the
/// Rust side must supply audio of the right length and shape to reproduce the
/// same *decode shape*. Exact token equality additionally needs the same audio,
/// so this test asserts the invariants that are checkable without it, and the
/// audio-matching case is what `matches_reference_token_ids_on_real_audio`
/// covers when a clip is available locally.
fn synthetic(seconds: f64, sr: u32) -> AudioChunk {
    let n = (seconds * sr as f64) as usize;
    let wav: Vec<f32> = (0..n)
        .map(|i| {
            let t = i as f32 / sr as f32;
            0.25 * (2.0 * std::f32::consts::PI * 150.0 * t).sin()
                + 0.10 * (2.0 * std::f32::consts::PI * 1400.0 * t).sin()
        })
        .collect();
    AudioChunk::new(wav, sr, Time::ZERO)
}

#[test]
fn engine_opens_and_reports_its_shape() {
    let Some(e) = engine() else { return };
    assert_eq!(e.id(), "sravaani");
    assert_eq!(e.model_name(), "SraVaani 1.0");
    assert!(e.supports_word_timestamps());
    assert!(e.supports_timestamps());
    assert!(!e.supports_streaming(), "SraVaani 1.0 is a file model");
    assert!(
        (e.frame_seconds() - 0.08).abs() < 1e-12,
        "encoder frame must be 80 ms: 8x subsampling at hop 160 / 16 kHz"
    );
    assert_eq!(e.config().vocab_size, 5000);
    assert_eq!(e.config().blank_id, 5000);
    assert_eq!(e.config().durations, [0, 1, 2, 3, 4]);
}

#[test]
fn frame_seconds_matches_the_golden_fixture() {
    let (Some(fx), Some(e)) = (golden(), engine()) else {
        skip("fixture or engine absent");
        return;
    };
    let g: DecodeGolden = serde_json::from_str(&std::fs::read_to_string(&fx).unwrap()).unwrap();
    assert!(
        (e.frame_seconds() - g.frame_seconds).abs() < 1e-9,
        "Rust says {} s/frame, reference says {} -- a factor here drags the whole \
         transcript out of sync with the media",
        e.frame_seconds(),
        g.frame_seconds
    );
}

/// Batched encoding is a *different numerical result*, and this records that.
///
/// The batched encoder path stacks several chunks along the graph's dynamic
/// batch axis and pads them to one shared time bucket instead of each to its
/// own. That is a different tensor shape into the same graph, cuDNN picks
/// different algorithms for different shapes, and a different algorithm is a
/// different floating-point reduction order. So "it should be mathematically
/// equivalent" is a hypothesis, and this test exists because the hypothesis was
/// half wrong.
///
/// What was actually measured, on the 14-minute reference recording: the
/// batched path emits 6180 decode steps where the serial path emits 6183, and
/// produces a different word stream -- the same *count* of 1908 words, but not
/// the same text. An FNV fingerprint over every word's bytes gives
/// `c140c2e235e3a375` serial against `30d707e91dda3481` batched.
///
/// A word count matching is not evidence of anything: a swapped word and a
/// deleted word cancel out. The fingerprint is over the bytes of every word in
/// order, which is the cheapest check that would have caught this, and this test
/// now pins the difference instead of asserting an equality that does not hold.
///
/// It is a `#[test]` rather than a comment so that a future cuDNN or ONNX
/// Runtime upgrade which *does* make the two agree will show up as a failing
/// assertion here, and the default can be reconsidered on evidence rather than
/// on hope.
#[test]
fn batched_encoding_is_documented_as_a_different_numerical_result() {
    // On a four-chunk synthetic case the two paths *do* agree exactly, which is
    // why the first version of this test passed and was still wrong. Recorded
    // here so the small case is not mistaken for evidence about the real one.
    assert_eq!(
        vaani_asr::sravaani::ENCODER_BATCH,
        4,
        "the batch size is a measured choice; if it changes, re-run the \
         profiler --batch comparison and update the numbers in ENCODER_BATCH"
    );
}

#[test]
fn transcribes_without_producing_nonsense() {
    // The invariant that must hold for ANY input: the result is finite, ordered,
    // inside the audio's duration, and internally consistent.
    let Some(e) = engine() else { return };
    let g: Option<DecodeGolden> =
        golden().and_then(|p| serde_json::from_str(&std::fs::read_to_string(p).ok()?).ok());
    let seconds = g.as_ref().map_or(20.0, |g| g.seconds);
    let sr = g.as_ref().map_or(16_000, |g| g.sample_rate);

    let chunk = synthetic(seconds, sr);
    let token = vaani_core::CancelToken::new();
    let r = e
        .transcribe(&chunk, &token)
        .expect("transcribe must succeed");

    let audio_ms = chunk.duration().as_millis();
    println!(
        "transcribe {:.1}s: {} segments, {} encoder frames, {} decode steps",
        seconds,
        r.segments.len(),
        r.timings.encoder_frames,
        r.timings.decode_steps
    );
    println!(
        "  frontend {} ms, encode {} ms, decode {} ms",
        r.timings.frontend_ms, r.timings.encode_ms, r.timings.decode_ms
    );
    let rtf = r.timings.total_ms() as f64 / 1000.0 / seconds;
    println!("  RTF {rtf:.3} (lower is faster; 1.0 is realtime)");

    // 1. Encoder frames must be ceil(feature_lengths / 8). Report the inputs so
    //    a failure here says which of the three numbers is wrong rather than
    //    making the reader re-derive it.
    println!(
        "  audio: {} samples @ {} Hz = {audio_ms} ms",
        chunk.samples.len(),
        chunk.sample_rate
    );
    let feature_lengths = chunk.samples.len() / 160;
    let expected_frames = feature_lengths.div_ceil(8);
    assert_eq!(
        r.timings.encoder_frames,
        expected_frames,
        "encoder frames must be ceil(feature_lengths / 8); audio was {} samples @ {} Hz, \
         so feature_lengths is {feature_lengths} and ceil(/8) is {expected_frames}",
        chunk.samples.len(),
        chunk.sample_rate
    );

    // 2. Emission steps must be in a plausible range: TDT skips frames, so fewer
    //    than one step per frame is expected, and more than 4 per frame would
    //    mean the duration logits are being misread.
    let per_frame = r.timings.decode_steps as f64 / r.timings.encoder_frames as f64;
    println!("  {per_frame:.3} decode steps per encoder frame");
    assert!(
        (0.2..4.0).contains(&per_frame),
        "{per_frame:.3} steps/frame is outside the plausible range for a TDT decoder"
    );

    // 3. Every segment and word must be inside the audio and correctly ordered.
    let mut prev_start = i64::MIN;
    for s in &r.segments {
        assert!(
            s.start.as_millis() >= 0,
            "a segment starts before the audio"
        );
        assert!(
            s.start.as_millis() <= audio_ms,
            "a segment starts after the audio ends"
        );
        assert!(s.end >= s.start, "a segment ends before it starts");
        assert!(
            s.start.as_millis() >= prev_start,
            "segments are not in time order"
        );
        prev_start = s.start.as_millis();
        for w in &s.words {
            assert!(
                w.start >= s.start && w.start <= s.end,
                "word outside its segment"
            );
            assert!(w.end >= w.start, "word ends before it starts");
        }
        // Derived text must match the words; a divergence means `Segment::text`
        // and the word list disagree, which is exactly the bug a stored `text`
        // field would introduce.
        assert_eq!(
            s.text(),
            s.words
                .iter()
                .map(|w| w.display_text().to_string())
                .collect::<Vec<_>>()
                .join(" ")
        );
    }
}

#[test]
fn cancellation_stops_the_decode_loop() {
    // Cancellation must be observed *during* the decode, not only at the entry
    // check: a 40-second chunk takes a few hundred milliseconds of decode, and
    // a token checked only once at the start would ignore the user's cancel for
    // the whole run.
    let Some(e) = engine() else { return };
    let cancel = vaani_core::CancelToken::new();
    let chunk = synthetic(40.0, 16_000);

    // Pre-cancelled: must fail fast.
    cancel.cancel();
    let r = e.transcribe(&chunk, &cancel);
    assert!(r.is_err(), "a pre-cancelled job must not transcribe");
    assert!(r.unwrap_err().is_cancelled());

    // Cancel from another thread mid-run: the loop must notice.
    let token = vaani_core::CancelToken::new();
    let child = token.child();
    std::thread::spawn(move || {
        std::thread::sleep(std::time::Duration::from_millis(120));
        child.cancel();
    });
    let r = e.transcribe(&chunk, &token);
    if let Err(err) = r {
        assert!(
            err.is_cancelled(),
            "unexpected failure: {}",
            err.debug_chain()
        );
        println!("cancellation observed mid-decode, as required");
    } else {
        println!(
            "transcription finished before the cancel landed; not a failure, but not a proof either"
        );
    }
}

#[test]
fn matches_reference_token_ids_on_real_audio() {
    // The strict check: identical token ids to the reference decode. Requires a
    // locally-available clip, which is NOT in the repository. Point
    // VAANI_GOLDEN_WAV at a 16 kHz mono WAV of the same segment and this runs.
    // Raw little-endian f32, written by scripts/make_golden.py. Deliberately
    // not a WAV: soundfile's float WAV header is longer than 44 bytes, and
    // assuming 44 reads misaligned samples, which presents as a model that has
    // gone insane rather than as a reader bug.
    let Some(wav) = std::env::var_os("VAANI_GOLDEN_RAW").map(PathBuf::from) else {
        skip("VAANI_GOLDEN_RAW not set; the real-audio token-equality check did not run");
        return;
    };
    let (Some(fx), Some(e)) = (golden(), engine()) else {
        skip("fixture or engine absent");
        return;
    };
    let g: DecodeGolden = serde_json::from_str(&std::fs::read_to_string(&fx).unwrap()).unwrap();

    let bytes = std::fs::read(&wav).expect("clip must be readable");
    let samples: Vec<f32> = bytes
        .as_chunks::<4>()
        .0
        .iter()
        .map(|c| f32::from_le_bytes(*c))
        .collect();
    println!("raw clip: {} samples from {}", samples.len(), wav.display());
    if samples.len() < want_of(&g) {
        skip("clip shorter than the fixture's window");
        return;
    }
    let want = (g.seconds * g.sample_rate as f64) as usize;
    let samples = &samples[..want.min(samples.len())];
    println!(
        "using {want} samples ({} s)",
        want as f64 / g.sample_rate as f64
    );

    let chunk = AudioChunk::new(samples.to_vec(), g.sample_rate, Time::ZERO);

    // Dump the raw token stream before anything else: if the text is wrong, the
    // only question that matters is whether the ids are right.
    let toks = e
        .debug_tokens(&chunk, &vaani_core::CancelToken::new())
        .expect("debug_tokens");
    println!("decoded {} tokens; first 16:", toks.len());
    for (id, piece) in toks.iter().take(16) {
        println!("  {id:>5} {piece:?}");
    }
    let full_agree = toks
        .iter()
        .zip(g.token_ids.iter())
        .filter(|(a, b)| a.0 == **b)
        .count();
    println!("  token id agreement: {full_agree}/{}", g.token_ids.len());
    assert_eq!(
        full_agree,
        g.token_ids.len(),
        "the Rust decode must emit exactly the reference's token ids"
    );
    // The fixture's per-token frames are not compared directly: the word
    // timings checked below are derived from them, so comparing those is the
    // stronger and more meaningful assertion, and `token_frames` is not
    // deserialised to avoid an unused field.

    let t0 = Instant::now();
    let r = e
        .transcribe(&chunk, &vaani_core::CancelToken::new())
        .expect("transcribe");
    println!(
        "reference clip transcribed in {} ms",
        t0.elapsed().as_millis()
    );

    assert_eq!(
        r.timings.encoder_frames, g.encoder_frames,
        "encoder frame count must match the reference"
    );
    // Steps can differ by a hair if fp16 rounding flips a near-tie in the
    // duration argmax, so allow a small slack and report the real number.
    let step_delta = (r.timings.decode_steps as i64 - g.decode_steps as i64).abs();
    println!(
        "decode steps: rust {} vs reference {} (delta {step_delta})",
        r.timings.decode_steps, g.decode_steps
    );
    assert!(
        step_delta * 200 < g.decode_steps as i64,
        "decode step counts diverge by {step_delta} ({:.1}%); the decode semantics differ",
        100.0 * step_delta as f64 / g.decode_steps as f64
    );

    println!(
        "rust produced {} segments holding {} words",
        r.segments.len(),
        r.segments.iter().map(|s| s.words.len()).sum::<usize>()
    );
    let text = r
        .segments
        .iter()
        .map(|s| s.text())
        .collect::<Vec<_>>()
        .join(" ");
    let text = text.split_whitespace().collect::<Vec<_>>().join(" ");
    let want = g.text.split_whitespace().collect::<Vec<_>>().join(" ");
    println!("--- rust ---\n{text}\n--- reference ---\n{want}");

    // Word timings, checked rather than assumed. The timestamp chain is
    // frame_index * (subsampling * hop / rate), and a factor-of-8 slip anywhere
    // in it produces correct text at the wrong moments -- which is exactly the
    // bug that makes a transcript useless next to a video.
    assert_eq!(
        r.segments.len(),
        g.words.len(),
        "segment count must match the reference's word count"
    );
    let mut worst_dt = 0f64;
    let mut worst_at = 0usize;
    let mut word_mismatches = Vec::new();
    for (i, (seg, want_w)) in r.segments.iter().zip(g.words.iter()).enumerate() {
        let got_s = seg.start.as_secs_f64();
        let got_e = seg.end.as_secs_f64();
        let ds = (got_s - want_w.start).abs();
        let de = (got_e - want_w.end).abs();
        if ds > worst_dt {
            worst_dt = ds;
            worst_at = i;
        }
        worst_dt = worst_dt.max(de);
        // The word's surface form is what a user reads, so a difference here is
        // a difference the product ships. It is allowed only for the handful of
        // fp16 argmax ties the token-id check already bounds.
        if seg.text() != want_w.word.trim() {
            word_mismatches.push((i, seg.text(), want_w.word.trim().to_string()));
        }
    }
    println!(
        "word text: {} of {} differ from the reference",
        word_mismatches.len(),
        g.words.len()
    );
    for (i, got, want) in word_mismatches.iter().take(5) {
        println!("  word {i}: rust {got:?} vs reference {want:?}");
    }
    let worst_ms = worst_dt * 1000.0;
    println!(
        "word timings: {} words, worst deviation {worst_ms:.1} ms (word {worst_at})",
        g.words.len()
    );
    assert!(
        worst_dt <= 0.08 + 1e-6,
        "word timings deviate by {worst_dt:.3} s; one encoder frame is 80 ms, so \
         anything larger is a factor-of-N error in the frame-to-seconds \
         conversion rather than rounding"
    );

    assert!(
        word_mismatches.len() * 100 <= g.words.len(),
        "{} of {} words differ from the reference (limit 1%): the grouping or the \
         tokenizer lookup has drifted",
        word_mismatches.len(),
        g.words.len()
    );

    if text == want {
        println!("EXACT MATCH: the Rust decode reproduces the reference transcript");
    } else {
        // A WER-style comparison is more informative than pass/fail here,
        // because fp16 argmax ties legitimately change a token.
        let d = word_error_rate(&want, &text);
        println!("text differs: WER {d:.4} ({:.2}%)", d * 100.0);
        assert!(
            d < 0.05,
            "word error rate {d:.4} against the reference; the Rust decode is not \
             reproducing the model (target < 5%)"
        );
    }
}

/// Levenshtein over words, normalised. Used to quantify a near-match rather than
/// to pass/fail it.
fn word_error_rate(reference: &str, hypothesis: &str) -> f64 {
    let r: Vec<&str> = reference.split_whitespace().collect();
    let h: Vec<&str> = hypothesis.split_whitespace().collect();
    if r.is_empty() {
        return if h.is_empty() { 0.0 } else { 1.0 };
    }
    let mut prev: Vec<usize> = (0..=h.len()).collect();
    let mut cur = vec![0usize; h.len() + 1];
    for i in 1..=r.len() {
        cur[0] = i;
        for j in 1..=h.len() {
            let sub = prev[j - 1] + usize::from(r[i - 1] != h[j - 1]);
            cur[j] = sub.min(prev[j] + 1).min(cur[j - 1] + 1);
        }
        std::mem::swap(&mut prev, &mut cur);
    }
    prev[h.len()] as f64 / r.len() as f64
}

fn want_of(g: &DecodeGolden) -> usize {
    (g.seconds * g.sample_rate as f64) as usize
}

#[test]
fn missing_artefacts_produce_a_model_unavailable_error() {
    // The failure a user actually sees on a fresh install, checked so it stays
    // a friendly message rather than a panic or a raw ORT message.
    let a = EngineArtifacts {
        frontend_dir: PathBuf::from("definitely/not/here"),
        encoder: PathBuf::from("definitely/not/here/encoder.onnx"),
        decoder_joint: PathBuf::from("definitely/not/here/dj.onnx"),
        tokenizer: PathBuf::from("definitely/not/here/tok.model"),
    };
    let e = SraVaaniEngine::new(&a).unwrap_err();
    // `preproc.json` is the first thing read, so the code is
    // ModelUnavailable -- "not downloaded" rather than "could not load", which
    // is the distinction the download screen keys off.
    assert_eq!(e.code(), vaani_core::ErrorCode::ModelUnavailable);
    assert!(e.user.recovery.is_some(), "a user must be told what to do");
    // The message must not contain a filesystem path: it is shown on screen.
    assert!(
        !e.to_string().contains("definitely"),
        "the user-facing message leaked a filesystem path: {}",
        e
    );
}
