    #[test]
    fn a_filter_string_is_never_interpreted_as_sql() {
        let (dir, s) = store();
        s.upsert_job(&job("j", &dir.join("a.wav"))).unwrap();
        // A quote, a wildcard and a semicolon must all be literal.
        for needle in ["%_", "'; DROP TABLE jobs; --", "' OR 1=1 --"] {
            let f = JobFilter::default().with_name(needle);
            let page = s.list_jobs(&f, 10, 0).unwrap();
            assert!(page.jobs.is_empty(), "{needle} matched something");
        }
        // The table is still there.
        assert_eq!(s.list_jobs(&JobFilter::default(), 10, 0).unwrap().total, 1);
    }

    #[test]
    fn a_wildcard_in_the_filter_matches_nothing_by_default() {
        let (dir, s) = store();
        s.upsert_job(&job("j", &dir.join("standup.wav"))).unwrap();
        // `%` is escaped, so it does not act as a wildcard.
        assert_eq!(
            s.list_jobs(&JobFilter::default().with_name("%"), 10, 0)
                .unwrap()
                .total,
            0
        );
    }

